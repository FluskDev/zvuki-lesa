/**
 * Утилиты для работы с датами без timezone-сдвигов.
 *
 * Проблема: `Date.toISOString()` возвращает дату в UTC, а не в локальном
 * времени пользователя. Если пользователь в Москве (UTC+3) выбирает в
 * календаре «16 августа», объект Date содержит 2026-08-16T00:00:00
 * локального MSK = 2026-08-15T21:00:00Z UTC, и `.toISOString().slice(0, 10)`
 * возвращает `2026-08-15` — на день раньше. Сервер сохраняет этот сдвинутый
 * день и присылает уведомления с неправильной датой заезда.
 *
 * Решение: формировать `YYYY-MM-DD` из ЛОКАЛЬНЫХ компонентов даты
 * (getFullYear / getMonth / getDate), а не из UTC. Серверный `parseISO`
 * делает обратное преобразование (из строки → локальная полночь), поэтому
 * round-trip остаётся согласованным.
 */

/**
 * Возвращает ISO-дату `YYYY-MM-DD` по локальному календарю пользователя.
 * Для `new Date(2026, 7, 16)` (16 августа локально) вернёт `'2026-08-16'`.
 */
export function formatLocalDateISO(date: Date): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Возвращает «сегодня» в локальном часовом поясе пользователя в формате
 * `YYYY-MM-DD`. Удобно для дефолтных границ календаря и фильтров.
 */
export function todayLocalISO(): string {
  return formatLocalDateISO(new Date());
}